/**
 * scripts/build-offline-payloads.ts
 *
 * Writes assets/offline/payloads.json: the 150 generated benchmark payloads,
 * already encoded in all three formats, for the app's offline Quick test.
 *
 *   node --experimental-strip-types scripts/build-offline-payloads.ts
 *
 * The bytes are not re-encoded here. They are fetched from dishcovery-proxy,
 * started by this script in local mode, so they are by construction the bytes
 * the proxy serves, produced by the frozen serializeRecipe. The 100 Spoonacular
 * payloads are filtered out and never written.
 *
 * Each buffer is stored as base64 with its SHA-256. Run
 * scripts/verify-offline-payloads.ts afterwards; it checks the file against a
 * fresh proxy and against the published payload sizes.
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { ROUTES, SERIALIZATION_FORMATS, type DatasetResponse } from '../shared/contract.ts';
import { startProxy } from './proxyProcess.ts';

export const OFFLINE_FILE = path.join(import.meta.dirname, '..', 'assets', 'offline', 'payloads.json');
const PORT = 3311;

const proxy = await startProxy(PORT);
try {
  const dataset = (await (await fetch(`${proxy.baseUrl}${ROUTES.dataset()}`)).json()) as DatasetResponse;
  const generated = dataset.entries
    .filter((e) => e.source === 'generated')
    .sort((a, b) => a.recipeId - b.recipeId);
  if (generated.length !== 150) throw new Error(`expected 150 generated entries, got ${generated.length}`);

  const entries = [];
  for (const e of generated) {
    const encoded: Record<string, string> = {};
    const sha256: Record<string, string> = {};
    const wireBytes: Record<string, number> = {};
    for (const format of SERIALIZATION_FORMATS) {
      const res = await fetch(`${proxy.baseUrl}${ROUTES.recipe(e.recipeId, format)}`);
      if (!res.ok) throw new Error(`${e.recipeId} ${format}: HTTP ${res.status}`);
      const bytes = Buffer.from(await res.arrayBuffer());
      encoded[format] = bytes.toString('base64');
      sha256[format] = createHash('sha256').update(bytes).digest('hex');
      wireBytes[format] = bytes.length;
    }
    entries.push({
      recipeId: e.recipeId,
      tier: e.tier,
      source: e.source,
      byteLength: e.byteLength,
      wireBytes,
      sha256,
      base64: encoded,
    });
  }

  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const file = {
    description:
      'The 150 generated Dishcovery benchmark payloads, encoded by dishcovery-proxy in JSON, ' +
      'MessagePack and Protocol Buffers. Generated by scripts/build-offline-payloads.ts; do not edit.',
    builtFromCommit: commit,
    count: entries.length,
    formats: SERIALIZATION_FORMATS,
    entries,
  };

  mkdirSync(path.dirname(OFFLINE_FILE), { recursive: true });
  writeFileSync(OFFLINE_FILE, JSON.stringify(file));
  const total = entries.reduce((a, e) => a + e.wireBytes.json + e.wireBytes.msgpack + e.wireBytes.protobuf, 0);
  console.log(
    `wrote ${path.relative(process.cwd(), OFFLINE_FILE)}: ${entries.length} payloads x 3 formats, ` +
      `${total.toLocaleString('en-US')} bytes of payload (built from ${commit.slice(0, 7)})`
  );
} finally {
  proxy.stop();
}
